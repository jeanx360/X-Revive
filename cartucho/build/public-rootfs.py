"""Prepare a staged public rootfs; never operates on host devices or the live OS."""
import argparse
import hashlib
import json
from pathlib import Path
import shutil


def prepare(root,repository):
    root=Path(root).resolve();repository=Path(repository).resolve()
    if root in (Path('/'),repository) or not (root/'var/lib/dpkg/status').is_file():
        raise ValueError('Expected an extracted, staged Debian rootfs')
    report=root/'usr/share/doc/xrevive/public-image.json'
    removed=json.loads(report.read_text()).get('removed',[]) if report.is_file() else []
    # AppRun is the binary itself. No RPATH/LD_LIBRARY_PATH uses these obsolete
    # AppImage libraries; the compiled Xemu links the Debian runtime libraries.
    for relative in ('opt/xemu/usr/lib','usr/local/lib/console/platform/firstrun/dash',
                     'usr/local/lib/console/platform/firstrun/bootanims'):
        path=root/relative
        if path.is_symlink():raise ValueError('Unexpected staged symlink: '+relative)
        if path.exists():
            shutil.rmtree(path);removed.append(relative)
    for pattern in ('usr/lib/firmware/xone_dongle_*.bin','var/lib/dkms/mok.key',
                    'etc/ssh/ssh_host_*_key','etc/ssl/private/*.key'):
        for path in root.glob(pattern):
            if path.is_symlink() or not path.is_file():raise ValueError('Unexpected private file')
            removed.append(str(path.relative_to(root)));path.unlink()
    # A machine identity is generated by the live system, not shared in the IMG.
    identity=root/'etc/machine-id'
    if identity.exists() and not identity.is_symlink():identity.write_text('')
    docs=root/'usr/share/doc/xrevive';docs.mkdir(parents=True,exist_ok=True)
    for name in ('LICENSE','NOTICE.md','THIRD_PARTY_NOTICES.md'):
        shutil.copy2(repository/name,docs/name)
    forbidden=[]
    for path in root.rglob('*'):
        if not path.is_file() or path.is_symlink():continue
        if path.name in ('bios.bin','mcpx_1.0.bin','eeprom.bin','BootAnim.xbe') or path.suffix.lower() in ('.xbe','.iso','.qcow2'):
            forbidden.append(str(path.relative_to(root)))
    if forbidden:raise ValueError('User-owned Xbox data in rootfs: '+str(forbidden))
    result=dict(schema=1,public=True,owner_firmware_included=False,apps_collection_included=False,
                dongle_firmware_included=False,removed=removed,
                xemu_sha256=hashlib.sha256((root/'opt/xemu/usr/bin/xemu').read_bytes()).hexdigest())
    (docs/'public-image.json').write_text(json.dumps(result,indent=2)+'\n')
    return result


if __name__=='__main__':
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('rootfs');ap.add_argument('repository');a=ap.parse_args()
    print(json.dumps(prepare(a.rootfs,a.repository),indent=2))
